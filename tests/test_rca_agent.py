import asyncio
import json

from app.agents.rca_agent import RCAAgent

async def main():
    agent = RCAAgent()
    result = await agent.investigate(
        "Investigate the checkout service timeout that occurred on "
        "2026-10-13 at approximately 14:01:18 UTC. "
        "Checkout failed while calling the email service. "
        "Correlate checkout and email service logs around the incident "
        "timestamp and identify the most likely root cause."
    )

    print("\n===== EVIDENCE VALIDATION =====")

    validation = result.get("validation")
    print(json.dumps(validation, indent=2))
    
    print("\n===== GROUNDING AUDIT =====")
    audit = result.get("grounding_audit", {})
    print(json.dumps(audit,indent=2, default=str))

    assert validation is not None, (
        "RCAAgent did not return validation metadata."
    )

    assert validation["is_valid"] is True
    assert validation["errors"] == []

    assert "grounding_audit" in result
    assert audit["status"] in {
        "completed",
        "partial",
    }

    assert audit["deterministic"] is not None
    semantic_status = audit["semantic"]["status"]

    assert semantic_status in {
        "completed",
        "not_applicable",
        "timedout",
        "failed",
    }

    if semantic_status == "completed":
        expected_finding_ids = {
            finding["finding_id"] for finding in result["rca_report"]["confirmed_findings"]
        }

        actual_finding_ids = {
            item["finding_id"] for item in audit["semantic"]["evaluations"]
        }
        
        # Original findings generated by Gemini
        original_finding_ids = {
            finding["finding_id"]
            for finding in result["original_rca_report"]["confirmed_findings"]
        }

        # Findings retained as confirmed
        confirmed_finding_ids = {
            finding["finding_id"]
            for finding in result["rca_report"]["confirmed_findings"]
        }

        # Findings requiring additional investigation
        provisional_finding_ids = {
            finding["finding_id"]
            for finding in result["rca_report"]["provisional_findings"]
        }

        # Findings rejected by grounding enforcement
        rejected_finding_ids = {
            finding["finding_id"]
            for finding in result["rca_report"]["rejected_findings"]
        }

        # Every original finding must appear in exactly one category.
        all_enforced_ids = (
            confirmed_finding_ids
            | provisional_finding_ids
            | rejected_finding_ids
        )

        assert all_enforced_ids == original_finding_ids

        # Categories must not overlap.
        assert confirmed_finding_ids.isdisjoint(provisional_finding_ids)
        assert confirmed_finding_ids.isdisjoint(rejected_finding_ids)
        assert provisional_finding_ids.isdisjoint(rejected_finding_ids)

        # Verify that the report agrees with the enforcement engine.
        enforcement = result["grounding_enforcement"]

        assert confirmed_finding_ids == {
            finding["finding_id"]
            for finding in enforcement["confirmed_findings"]
        }

        assert provisional_finding_ids == {
            finding["finding_id"]
            for finding in enforcement["provisional_findings"]
        }

        assert rejected_finding_ids == {
            finding["finding_id"]
            for finding in enforcement["rejected_findings"]
        }

        # Verify counts.
        assert len(confirmed_finding_ids) == enforcement["confirmed_count"]
        assert len(provisional_finding_ids) == enforcement["provisional_count"]
        assert len(rejected_finding_ids) == enforcement["rejected_count"]

        print("PASS: Grounding enforcement preserved and classified all findings")

    if result.get("rca_report"):
        print("\n===== STRUCTURED RCA REPORT =====")
        print(
            json.dumps(
                result["rca_report"],
                indent=2
            )
        )
    print("\nTool History:")

    for tool in result["tool_history"]:
        print(
            f"Iteration {tool['iteration']}: "
            f"{tool['tool']}"
            f"{tool['arguments']}"
            f"[{tool['status']}]"
        )

    print ("\nToken Usage:")

    for key, value in result["token_usage"].items():
        print(f"{key}: {value}")

    print("\nRCA Report:")
    print(result["answer"])

    print("\n===== EVIDENCE SUMMARY =====")
    print("Evidence count:", result["evidence_count"])

    for evidence in result["evidence"][:10]:
        print(
            evidence["evidence_id"],
            evidence["source"],
            evidence["summary"][:120],
        )
    
    report = result["rca_report"]
    if report["completion_reason"] == "investigation_saturated":
        assert report["status"] == "partial"
        print("PASS: Saturation does not imply completed RCA")

    elif report["completion_reason"] == "iteration_limit":
        assert report["status"] == "partial"
        print("PASS: Iteration limit produces partial RCA")

    else:
        print(
            "INFO: Investigation completed with reason:",
            report["completion_reason"]
        )

if __name__ == "__main__":
    asyncio.run(main())